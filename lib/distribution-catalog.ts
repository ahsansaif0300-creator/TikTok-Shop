export function flattenDistributionCatalog(): CatalogDraft[] {
  const rows: CatalogDraft[] = [];
  for (const category of STORE_CATEGORIES) {
    const items = RAW[category];
    if (!items || items.length < 25) {
      throw new Error(`Catalog incomplete for ${category}`);
    }
    items.slice(0, 25).forEach((item, index) => {
      rows.push({
        category,
        title: item[0],
        selling: item[1],
        margin: m(index),
        blurb: item[2],
      });
    });
  }
  return rows;
}

