export function catalogSku(category: string, index: number) {
  return `DC-${categorySlug(category).slice(0, 18)}-${String(index + 1).padStart(2, "0")}`;
}

export function pricedDistributionCatalog() {
  const counts: Record<string, number> = {};
  return flattenDistributionCatalog().map((draft) => {
    const index = counts[draft.category] ?? 0;
    counts[draft.category] = index + 1;
    return rememberCatalogRow(pricedCatalogRow(draft, index));
  });
}

export function pricedCatalogRow(draft: CatalogDraft, index: number) {
  const priced = costFromSelling(draft.selling, draft.margin);
  const sku = catalogSku(draft.category, index);
  return {
    ...draft,
    ...priced,
    sku,
    image: catalogPhotoPath(sku),
    description: `${draft.title}. ${draft.blurb} Cost and selling prices are stored separately so listing status can change without duplicating the SKU.`,
  };
}

